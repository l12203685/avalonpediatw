function dataReadingGuide(role: string, side: 'good' | 'evil'): string {
  const faction = side === 'good' ? '藍方' : '紅方';
  const relation = side === 'good'
    ? '藍方的最終勝率＝任務結果 × 刺殺結果（先打到三藍，再讓梅林活下來）。'
    : '紅方的最終勝率＝任務結果 ＋（1 − 任務結果）× 刺殺結果（三紅直接贏；沒有三紅的局，再靠刺中梅林）。';
  return `## 數字怎麼讀

- **一局只有三種結果**：三紅（紅方做滿三次失敗任務）、三藍死（藍方三次任務成功，但梅林被刺中）、三藍活（三次成功，梅林沒被刺中）。
- **三藍死算紅方贏**：照規則，藍方要完成三次任務，**而且**梅林沒被刺中才獲勝（見[遊戲基本規則與流程](wiki:wiki-63)）。所以好人勝＝三藍活；紅方勝＝三紅或三藍死。
- **任務結果**：只看任務。三藍（不論梅林死活）＝藍方贏，三紅＝紅方贏；n＝全部局數。
- **刺殺結果**：只看打到三藍的局。三藍活＝藍方贏，三藍死＝紅方贏；n＝三藍局數（三紅的局沒有刺殺，不算）。
- **遊戲結果**：就是最終勝率。三藍活＝藍方贏，三紅和三藍死都算紅方贏；n＝全部局數。
- **每一格都是${role}所屬陣營（${faction}）贏的比例**，旁邊的 n 是分母；淡色＝樣本太少，不要拿來下結論。
- **三塊的關係**：${relation}`;
}

