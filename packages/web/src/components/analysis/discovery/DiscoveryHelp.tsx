import { STRATEGY_MIN_DIFF } from '@avalon/shared/stats';
import { InfoTip } from '../ui';

/** 自動發現的方法說明（每個區塊旁的 ⓘ）。 */
export default function DiscoveryHelp({ tests }: { tests?: number }): JSX.Element {
  return (
    <InfoTip title="自動發現怎麼算">
      把篩選後的局拆成局、提議、任務、湖中女神、座位五種單位（加上下面的三種新資料），每個維度（陣容強度、座位、角色、局勢、分類…）都跟每個指標
      （結果、派隊、投票、任務、湖、角色決策、失誤）比一次：數值維度比前 1/3 和後 1/3，類別維度比某一類和其他。比率用兩比例
      z 檢定、平均用 Welch 檢定，{tests ? `這次一共 ${tests} 個檢定，` : ''}用 Benjamini–Hochberg 控制錯誤發現率，只列 q ≤ 0.05、
      每組至少 30 個樣本的結果，依效果量排序。定義上就會相關的組合（例：隊長是紅方 × 隊上有紅）不比。局勢看的是任務結果的順序（紅藍藍紅跟藍紅紅藍不同），
      也可以再加上湖中宣告；比分（不看順序）跟順序都有差時只列順序那一層。局勢、第幾輪這類遊戲結構造成的差異預設不列，可以打開。這些都是相關，不是因果：例如強的玩家常常一起打，某個維度的差異可能其實來自桌上整體強度
      （卡片會標出跟 S 高度相關、以及在 S 分層內再比一次的差）。
      <br />
      新資料（兩紅之後的派隊、關鍵外白／內黑與全部投票，只看第 3～5 局）另外拆成三種單位：兩紅後的提議、關鍵票、藍方投票（同一局同一座位同一局數合成一列），
      維度有做事的人的分組（強者 vs 新手）、桌的分組（高端 vs 歡樂；切點跟著分組九宮格調的值）、角色、座位、第幾局、第幾次、局勢。同一局的幾次提議、同一位玩家
      在很多局的票彼此相關，所以這三種用叢集穩健的檢定（局與玩家兩個方向，等於用局、玩家當重抽單位），每組至少 20 局、10 位有寫名字的玩家才比，跟其他檢定一起做
      Benjamini–Hochberg。每項附一句「可能的策略」：一律是假設（觀察資料，相關不是因果），只寫組名、不寫玩家；差距不到 {STRATEGY_MIN_DIFF} 個百分點、維度是角色、或在同一個角色裡比
      就沒差（例：梅林看得到拇指）時不給。
    </InfoTip>
  );
}
